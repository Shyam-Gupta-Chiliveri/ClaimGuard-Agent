  function readLang() {
    const current = document.documentElement.lang;
    if (current === "de" || current === "en") return current;
    try {
      const q = new URLSearchParams(location.search).get("lang");
      if (q === "de" || q === "en") return q;
      const stored = localStorage.getItem("cg-lang");
      if (stored === "de" || stored === "en") return stored;
    } catch { /* private mode */ }
    return (navigator.language || "").toLowerCase().startsWith("de") ? "de" : "en";
  }

  let lang = readLang();
  const missing = new Set();

  function t(s, vars) {
    if (s == null) return "";
    const key = String(s);
    let out = key;
    if (lang === "de") {
      if (Object.prototype.hasOwnProperty.call(DE, key)) out = DE[key];
      else if (key.trim()) missing.add(key);
    }
    if (vars) {
      for (const name of Object.keys(vars)) out = out.split("{" + name + "}").join(String(vars[name] ?? ""));
    }
    return out;
  }

